import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { MARK_END, MARK_START, NAME } from './brand.mjs';
import { ReelkitError, log } from './log.mjs';
import { readJson } from './fsutil.mjs';
import { loadResults } from './state.mjs';
import { qaFile } from './manifest.mjs';
import { selectScenes, shotsFor } from './config.mjs';
import { motionBase } from './record.mjs';

const esc = (s) => String(s).replace(/"/g, '&quot;');

/** Builds the README block from assets that passed QA. Never references FAILED files. */
export function buildBlock(cfg, readmeDir) {
  const results = loadResults(cfg).assets;
  const qa = readJson(qaFile(cfg), { assets: {} }).assets;
  const pending = [];
  const ok = (file) => {
    const r = results[file];
    if (!r || r.status !== 'PASS' || !existsSync(path.join(cfg.outDir, file))) return false;
    const v = qa[file]?.visual?.verdict;
    if (v === 'fail') return false;
    if (v !== 'pass') pending.push(file);
    return true;
  };
  const url = (file) => path.relative(readmeDir, path.join(cfg.outDir, file)).split(path.sep).join('/');
  const picture = (light, dark, alt, width) => {
    const w = width ? ` width="${width}"` : '';
    if (light && dark && ok(light) && ok(dark)) {
      return `<picture>\n  <source media="(prefers-color-scheme: dark)" srcset="${url(dark)}">\n  <img src="${url(light)}" alt="${esc(alt)}"${w}>\n</picture>`;
    }
    const one = [light, dark].find((f) => f && ok(f));
    return one ? `<img src="${url(one)}" alt="${esc(alt)}"${w}>` : null;
  };

  const scenes = selectScenes(cfg, []);
  const parts = [];
  const m = cfg.marketing ?? {};

  // Hero: a framed GIF (linking to the MP4) for motion scenes, else the framed hero still.
  const hero = scenes.find((s) => s.name === m.hero);
  if (hero?.isMotion) {
    const base = motionBase(hero, shotsFor(hero)[0]);
    const gif = [`${base}-framed.gif`, `${base}.gif`].find(ok);
    const mp4 = [`${base}-framed.mp4`, `${base}.mp4`].find(ok);
    if (gif) parts.push(`<p align="center">\n  ${mp4 ? `<a href="${url(mp4)}">` : ''}<img src="${url(gif)}" alt="${esc(hero.title)}" width="880">${mp4 ? '</a>' : ''}\n</p>`);
  } else if (hero) {
    const pic = picture('hero-light.png', 'hero-dark.png', hero.title, 880);
    if (pic) parts.push(`<p align="center">\n${pic}\n</p>`);
  }

  if (m.trio) {
    const pic = picture(`${m.trio}-trio-light.png`, `${m.trio}-trio-dark.png`, `${cfg.name ?? ''} on desktop, tablet and phone`.trim(), 880);
    if (pic) parts.push(`<p align="center">\n${pic}\n</p>`);
  }

  // Gallery: one framed image per still scene (desktop first), light/dark aware.
  const wanted = cfg.readme?.gallery ?? scenes.filter((s) => s.isStill).map((s) => s.name);
  const cells = [];
  for (const name of wanted) {
    const scene = scenes.find((s) => s.name === name);
    if (!scene) continue;
    const vp = scene.viewports.find((v) => v.name === 'desktop') ?? scene.viewports[0];
    const id = `${scene.name}-${vp.name}`;
    const suffix = scene.outputs.includes('framed') ? '-framed' : '';
    const pic = picture(`${id}-light${suffix}.png`, `${id}-dark${suffix}.png`, scene.title);
    if (pic) cells.push(`<td width="50%" align="center">\n\n${pic}\n<br><sub>${scene.title}</sub>\n\n</td>`);
  }
  if (cells.length) {
    const rows = [];
    for (let i = 0; i < cells.length; i += 2) rows.push(`<tr>\n${cells.slice(i, i + 2).join('\n')}\n</tr>`);
    parts.push(`<table>\n${rows.join('\n')}\n</table>`);
  }

  // Remaining flows (not the hero) as linked GIFs.
  for (const scene of scenes.filter((s) => s.isMotion && s.name !== m.hero)) {
    const base = motionBase(scene, shotsFor(scene)[0]);
    const gif = [`${base}-framed.gif`, `${base}.gif`].find(ok);
    if (gif) parts.push(`<p align="center"><img src="${url(gif)}" alt="${esc(scene.title)}" width="720"><br><sub>${scene.title}</sub></p>`);
  }

  return { block: `${MARK_START}\n<!-- Generated by ${NAME}. Edit ${path.basename(cfg.file)}, then run \`${NAME} readme --write\`. -->\n${parts.join('\n\n')}\n${MARK_END}`, pending: [...new Set(pending)] };
}

export function insertBlock(text, block) {
  const s = text.indexOf(MARK_START);
  const e = text.indexOf(MARK_END);
  if (s !== -1 && e > s) return text.slice(0, s) + block + text.slice(e + MARK_END.length);
  if (s !== -1 || e !== -1) throw new ReelkitError('README has only one of the reelkit markers.', `Add both ${MARK_START} and ${MARK_END}, or remove the stray one.`);
  return `${text.replace(/\s*$/, '')}\n\n${block}\n`;
}

export async function readme(cfg, { write = false, file, quietIfMissing = false } = {}) {
  const target = path.resolve(cfg.root, file ?? cfg.readme.file);
  const { block, pending } = buildBlock(cfg, path.dirname(target));
  if (pending.length && !quietIfMissing) log.warn(`${pending.length} asset(s) in this block have no visual PASS yet; review them before publishing (reelkit verify).`);
  if (!write) {
    console.log(block);
    return;
  }
  const exists = existsSync(target);
  const current = exists ? readFileSync(target, 'utf8') : '';
  if (write === 'if-markers' && !current.includes(MARK_START)) return;
  const next = insertBlock(current, block);
  if (next === current) {
    log.ok(`${path.basename(target)} already up to date.`);
    return;
  }
  writeFileSync(target, next);
  log.ok(`Updated the ${NAME} block in ${path.relative(cfg.root, target) || path.basename(target)} (content outside the markers untouched).`);
}
